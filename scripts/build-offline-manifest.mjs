// 网页资源变化后运行；测试会检查清单，防止离线版本漏文件或混用旧资源。
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
const root = new URL('../', import.meta.url), html = readFileSync(new URL('index.html', root), 'utf8');
const assets = new Set(['./index.html', './songs.json', './songs_live.json', './catalogs/fiona.json', './catalogs/fiona-live.json', './lyrics/lyrics.json']);
for (const match of html.matchAll(/<(?:script|link)\b[^>]*?(?:src|href)="([^"]+)"[^>]*>/g)) {
    if (!/^(?:https?:|data:|#)/.test(match[1])) assets.add('./' + match[1].replace(/^\.\//, ''));
}
for (const name of ['index.css', 'personal.css']) {
    for (const match of readFileSync(new URL(name, root), 'utf8').matchAll(/url\(['"]?(\.\/imgs\/[^)'"\s]+)['"]?\)/g)) assets.add(match[1]);
}
for (const match of readFileSync(new URL('wardrobe.js', root), 'utf8').matchAll(/image: '(imgs\/[^']+)'/g)) assets.add('./' + match[1]);
for (const item of JSON.parse(readFileSync(new URL('manifest.webmanifest', root), 'utf8')).icons) assets.add('./' + item.src);
const paths = [...assets].sort(), hash = createHash('sha256');
for (const path of paths) { hash.update(path); hash.update(readFileSync(new URL(path.split('?')[0], root))); }
hash.update(readFileSync(new URL('sw.js', root)));
const output = '// Generated by node scripts/build-offline-manifest.mjs\nself.SG_OFFLINE_ASSETS = ' + JSON.stringify({ version: hash.digest('hex').slice(0, 16), paths }, null, 2) + ';\n';
const destination = new URL('offline-assets.js', root);
if (process.argv.includes('--check')) {
    if (readFileSync(destination, 'utf8') !== output) throw new Error('离线资源清单已过期，请运行 node scripts/build-offline-manifest.mjs');
} else writeFileSync(destination, output);
